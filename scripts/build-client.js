#!/usr/bin/env node
/**
 * Builds client.js, the plugin's one browser module, from each feature's own browser module
 * (features/<folder>/client.js, written in DSH's module format so it can be tested alone) and the
 * runtime that starts the features that are on (src/runtime.js). DSH loads one browser module per
 * package, so the features are joined here: each feature's `window.__ModuleLoader__.load(` becomes a
 * registration under its key. No other change is made to their text.
 *
 * `node scripts/build-client.js` writes client.js; `--check` exits 1 when client.js is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { FEATURES } from '../src/features.js'

const root = new URL('../', import.meta.url)
const read = path => readFileSync(new URL(path, root), 'utf8')
const LOAD = 'window.__ModuleLoader__.load('

/** The text of client.js for the current sources. */
export function buildClient() {
  const name = JSON.parse(read('package.json')).name
  const parts = Object.entries(FEATURES).filter(([, feature]) => feature.browser).map(([key, feature]) => {
    const source = read(`features/${feature.folder}/client.js`)
    const at = source.indexOf(LOAD)
    if (at === -1 || source.indexOf(LOAD, at + 1) !== -1) throw new Error(`features/${feature.folder}/client.js must call ${LOAD} exactly once`)
    return `// ---- features/${feature.folder}/client.js\n${source.slice(0, at)}feature(${JSON.stringify(key)}, ${source.slice(at + LOAD.length)}`
  })
  return [
    '/*',
    ` * Browser half of ${name}. Generated by scripts/build-client.js from each feature's`,
    ' * client.js and src/runtime.js: edit those, then run `npm run build`.',
    ' */',
    `window.__ModuleLoader__.load({`,
    `  id: ${JSON.stringify(name)},`,
    '  factory(require) {',
    '    const factories = new Map()',
    '    const feature = (key, { factory }) => { factories.set(key, factory) }',
    '',
    ...parts,
    '// ---- src/runtime.js',
    read('src/runtime.js'),
    '    return {',
    '      inject: [],',
    '      apply(ctx) { runFeatures(ctx, factories, require) },',
    '    }',
    '  },',
    '})',
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('client.js', root)
  const next = buildClient()
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(target, 'utf8') } catch { /* missing counts as out of date */ }
    if (current !== next) {
      console.error('client.js is out of date: run npm run build')
      process.exit(1)
    }
  } else {
    writeFileSync(target, next)
  }
}
